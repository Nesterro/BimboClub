using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;

namespace BimboClub.ExtraScheduleItems
{
    // ADSK GUIDs: OSTEC Revit guide, appendix 2 (see tests/ExtraScheduleItems/README.md).
    // One schema drives family creation, writing, reading and post-regeneration verification.
    internal static class ExtraScheduleParameterSchema
    {
        internal sealed class Field
        {
            public string Name => Names[0];
            public string[] Names { get; }
            public Guid Guid { get; }
            public bool IsNumber { get; }
            public Guid? LegacyGuid => LegacyGuids.TryGetValue(Name, out var guid) ? guid : (Guid?)null;
            private readonly Func<ExtraScheduleItem, object> read;

            public Field(string guid, bool number, Func<ExtraScheduleItem, object> read, params string[] names)
            {
                Guid = new Guid(guid);
                IsNumber = number;
                this.read = read;
                Names = names;
            }

            public object Value(ExtraScheduleItem item)
            {
                object value = read(item);
                if (!IsNumber) return NormalizeText(value as string);
                double number = (double)value;
                if (double.IsNaN(number) || double.IsInfinity(number))
                    throw new InvalidOperationException($"Недопустимое число в {Name}.");
                return number;
            }

            public bool Matches(object expected, object actual)
            {
                if (!IsNumber) return actual is string text && string.Equals((string)expected, text, StringComparison.Ordinal);
                return actual is double number && !double.IsNaN(number) && !double.IsInfinity(number) &&
                    Math.Abs((double)expected - number) <= 1e-9;
            }
        }

        // These IDs were mistakenly generated by old BCC releases. Read them before
        // migration so an empty/project-type ADSK parameter does not hide saved row data.
