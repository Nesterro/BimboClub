        };

        internal static Field Find(string[] names) => Fields.FirstOrDefault(f => names.Any(n => f.Names.Contains(n)));
        internal static string NormalizeText(string value) => (value ?? "").Trim();

        internal static void Write(ExtraScheduleItem item, Action<Field, object> write)
        {
            foreach (var field in Fields) write(field, field.Value(item));
        }

        // Call after all rows have been written and Revit has regenerated, so a value
        // accidentally shared by multiple rows is detected before committing the transaction.
        internal static void Verify(ExtraScheduleItem item, Func<Field, object> read, int? elementId = null)
        {
            foreach (var field in Fields)
            {
                object expected = field.Value(item);
                object actual = read(field);
                if (!field.Matches(expected, actual))
                    throw new InvalidOperationException($"Не удалось сохранить {field.Name} у элемента {elementId ?? item.Id}. " +
                        $"GUID {field.Guid}. Ожидалось: {Describe(expected)}; прочитано: {Describe(actual)}.");
            }
        }

        private static string Describe(object value)
        {
            if (value == null) return "<параметр отсутствует или имеет неверный тип>";
            string text = Convert.ToString(value, CultureInfo.InvariantCulture);
            int length = text.Length;
            if (length > 160) text = text.Substring(0, 160) + "…";
            text = text.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", "\\r")
                .Replace("\n", "\\n").Replace("\t", "\\t").Replace("\0", "\\0").Replace("\u00a0", "\\u00A0");
            return $"\"{text}\" (длина {length})";
        }
    }
