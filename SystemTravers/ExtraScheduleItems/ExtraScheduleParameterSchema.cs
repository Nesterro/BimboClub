            ["ADSK_Наименование"] = new Guid("e6e0f5cd-3e26-407b-9993-4a11be2454be"),
            ["ADSK_Марка"] = new Guid("809e51c8-c689-49c9-a548-8cf9c9162985"),
            ["ADSK_Количество"] = new Guid("8d0092c6-3023-455b-80fb-b0c4119d8504"),
            ["ADSK_Масса"] = new Guid("4b71f9cf-ff58-45f8-b32c-7b447432c668"),
            ["ADSK_Примечание"] = new Guid("e2a4beaa-43e7-4b77-8fa0-681e18ca4743")
